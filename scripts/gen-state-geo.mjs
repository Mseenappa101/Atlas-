// Generates per-state postcard geometry from the same us-atlas topojson the map uses, so outlines are
// accurate and consistent. For each state: an outline path fitted to the card viewBox, the centroid, and
// projected pin coords for curated legal-market cities. Output: src/data/states/geo/<code>.js (one small
// self-contained module per state, lazy-loaded with the state's data file).
//
// Run: node scripts/gen-state-geo.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { feature } from 'topojson-client';
import { geoPath, geoIdentity, geoAlbersUsa } from 'd3-geo';
import { US_STATES } from '../src/constants/states.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const topo = JSON.parse(readFileSync(join(ROOT, 'node_modules/us-atlas/states-albers-10m.json'), 'utf8'));
const features = feature(topo, topo.objects.states).features;

// us-atlas 10m is pre-projected with this exact AlbersUSA transform (975×610 frame); reuse it to place
// cities given as lat/lng into the same planar space the outlines live in.
const albers = geoAlbersUsa().scale(1300).translate([487.5, 305]);

const NAME_TO_CODE = Object.fromEntries(US_STATES.map((s) => [s.name, s.abbr]));
NAME_TO_CODE['District of Columbia'] = 'DC';

// Curated legal-market cities (lat, lng) for states that get hand-authored pins. Others get no pins here;
// the data file can add its own. TX ships in this pass; Tier 1 cities are added when those are built.
const CITIES = {
  TX: [
    { name: 'Dallas', lat: 32.7767, lng: -96.7970 },
    { name: 'Houston', lat: 29.7604, lng: -95.3698 },
    { name: 'Austin', lat: 30.2672, lng: -97.7431 },
    { name: 'San Antonio', lat: 29.4241, lng: -98.4936 },
  ],
  LA: [
    { name: 'New Orleans', lat: 29.9511, lng: -90.0715 },
    { name: 'Baton Rouge', lat: 30.4515, lng: -91.1871 },
    { name: 'Lafayette', lat: 30.2241, lng: -92.0198 },
    { name: 'Shreveport', lat: 32.5252, lng: -93.7502 },
  ],
  NY: [
    { name: 'New York', lat: 40.7128, lng: -74.0060 },
    { name: 'Buffalo', lat: 42.8864, lng: -78.8784 },
    { name: 'Albany', lat: 42.6526, lng: -73.7562 },
    { name: 'Rochester', lat: 43.1566, lng: -77.6088 },
  ],
  GA: [
    { name: 'Atlanta', lat: 33.7490, lng: -84.3880 },
    { name: 'Savannah', lat: 32.0809, lng: -81.0912 },
    { name: 'Augusta', lat: 33.4735, lng: -82.0105 },
    { name: 'Macon', lat: 32.8407, lng: -83.6324 },
  ],
  FL: [
    { name: 'Miami', lat: 25.7617, lng: -80.1918 },
    { name: 'Orlando', lat: 28.5383, lng: -81.3792 },
    { name: 'Tampa', lat: 27.9506, lng: -82.4572 },
    { name: 'Jacksonville', lat: 30.3322, lng: -81.6557 },
  ],
};

const W = 400;
const H = 288;
const PAD = 22;
const r = (n) => Math.round(n * 10) / 10;

mkdirSync(join(ROOT, 'src/data/states/geo'), { recursive: true });

let count = 0;
for (const f of features) {
  const code = NAME_TO_CODE[f.properties.name];
  if (!code) continue;

  const id = geoIdentity().fitExtent([[PAD, PAD], [W - PAD, H - PAD]], f);
  const draw = geoPath(id);
  const outline = draw(f);
  const centroid = draw.centroid(f).map(r);

  const pins = {};
  for (const c of CITIES[code] ?? []) {
    const planar = albers([c.lng, c.lat]);
    if (!planar) continue;
    const [px, py] = id(planar);
    pins[c.name] = [r(px), r(py)];
  }

  const body = { viewBox: [W, H], outline, centroid, pins };
  writeFileSync(
    join(ROOT, `src/data/states/geo/${code.toLowerCase()}.js`),
    `// Auto-generated by scripts/gen-state-geo.mjs — do not edit by hand.\nexport default ${JSON.stringify(body)};\n`
  );
  count += 1;
}
console.log(`wrote ${count} state geo modules to src/data/states/geo/`);
